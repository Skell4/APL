struct DeviceFormat {
    std::uint16_t channels = 0, bits = 0, validBits = 0, alignment = 0;
    std::uint32_t rate = 0;
    bool floating = false;
    int leftIndex = 0, rightIndex = 1;
    bool parse(const WAVEFORMATEX* f) noexcept {
        channels = f->nChannels; rate = f->nSamplesPerSec;
        bits = validBits = f->wBitsPerSample; alignment = f->nBlockAlign;
        floating = f->wFormatTag == WAVE_FORMAT_IEEE_FLOAT;
        DWORD mask = 0;
        if (f->wFormatTag == WAVE_FORMAT_EXTENSIBLE) {
            if (f->cbSize < 22) return false;
            const auto* x = reinterpret_cast<const WAVEFORMATEXTENSIBLE*>(f);
            const auto* subtype = reinterpret_cast<const unsigned char*>(&x->SubFormat);
            if (waveSubtype(subtype, 3)) floating = true;
            else if (waveSubtype(subtype, 1)) floating = false;
            else return false;
            validBits = x->Samples.wValidBitsPerSample;
            if (!validBits) validBits = bits;
            mask = x->dwChannelMask;
        } else if (f->wFormatTag != WAVE_FORMAT_PCM && !floating) return false;
        if (!channels || channels > 32 || !rate || alignment != channels * (bits / 8u)) return false;
        if (floating) { if ((bits != 32 && bits != 64) || validBits != bits) return false; }
        else if ((bits != 8 && bits != 16 && bits != 24 && bits != 32) ||
                 !validBits || validBits > bits) return false;
        if (mask && channels > 1) {
            leftIndex = rightIndex = -1;
            int index = 0;
            for (unsigned b = 0; b < 32; ++b) if (mask & (DWORD(1) << b)) {
                if (b == 0) leftIndex = index;
                if (b == 1) rightIndex = index;
                ++index;
            }
            if (index != channels || leftIndex < 0 || rightIndex < 0) return false;
        }
        return true;
    }
};

inline void encodeDevice(const Frame* source, std::size_t frames, unsigned char* output,
                         const DeviceFormat& f, Dither& dither) noexcept {
    const unsigned bytes = f.bits / 8;
    for (std::size_t i = 0; i < frames; ++i) {
        for (unsigned ch = 0; ch < f.channels; ++ch) {
            float sample = 0;
            if (f.channels == 1) sample = finiteAudio(source[i].left * 0.5f + source[i].right * 0.5f);
            else if (int(ch) == f.leftIndex) sample = source[i].left;
            else if (int(ch) == f.rightIndex) sample = source[i].right;
            sample = clampOutput(sample);
            auto* p = output + i * f.alignment + ch * bytes;
            if (f.floating) {
                if (f.bits == 32) std::memcpy(p, &sample, 4);
                else { const double value = sample; std::memcpy(p, &value, 8); }
            } else {
                const double scale = static_cast<double>(std::uint64_t(1) << (f.validBits - 1));

                const double noise = f.validBits == 16 && sample != 0.0f ? dither.tpdf() : 0.0;
                double quantized = std::floor(static_cast<double>(sample) * scale + noise + 0.5);
                quantized = (std::max)(-scale, (std::min)(scale - 1.0, quantized));
                const auto signedValue = static_cast<std::int64_t>(quantized);
                const auto raw = static_cast<std::uint32_t>(
                    f.bits == 8 ? signedValue + static_cast<std::int64_t>(scale) : signedValue)
                    << (f.bits - f.validBits);
                for (unsigned b = 0; b < bytes; ++b) p[b] = static_cast<unsigned char>(raw >> (8u * b));
            }
        }
    }
}

