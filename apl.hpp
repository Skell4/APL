class StreamReader {
    struct Page {
        std::uint64_t first = (std::numeric_limits<std::uint64_t>::max)();
        std::uint64_t used = 0;
        std::array<Frame, 2048> frames{};
    };
    Decoder& decoder_;
    std::array<Page, 4> pages_{};
    std::uint64_t clock_ = 0;
public:
    bool good = true;
    std::string error;
    explicit StreamReader(Decoder& d) : decoder_(d) {}
    Frame get(std::uint64_t index) {
        const auto first = index - index % 2048;
        Page* page = nullptr;
        for (auto& p : pages_) if (p.first == first) { page = &p; break; }
        if (!page) {
            page = &pages_[0];
            for (auto& p : pages_) if (p.used < page->used) page = &p;
            std::size_t read = 0;
            if (!decoder_.readFrames(first, 2048, page->frames.data(), read, error) ||
                index - first >= read) {
                good = false;
                if (error.empty()) error = "APL: frame audio richiesto non disponibile.";
                return {};
            }
            page->first = first;
        }
        page->used = ++clock_;
        return page->frames[static_cast<std::size_t>(index - first)];
    }
};

