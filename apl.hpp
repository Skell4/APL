struct Ramp {
    float current = 0.0f, target = 0.0f, step = 0.0f;
    std::uint32_t remaining = 0;
    void set(float value, std::uint32_t samples) noexcept {
        if (value == target) return;
        target = value;
        remaining = (std::max)(std::uint32_t(1), samples);
        step = (target - current) / static_cast<float>(remaining);
    }
    void reset(float value) noexcept { current = target = value; remaining = 0; step = 0; }
    float next() noexcept {
        if (remaining) { current += step; if (!--remaining) current = target; }
        return current;
    }
    bool silent() const noexcept { return current == 0.0f && remaining == 0; }
};

struct Timeline {
    std::uint64_t length = 0, overlap = 0, period = 0;
    double sourceRate = 0;
    explicit Timeline(const SourceFormat& f) noexcept : length(f.frames), sourceRate(f.sampleRate) {
        overlap = (std::min)(length / 4, static_cast<std::uint64_t>(sourceRate * loopOverlapSeconds));
        period = length - overlap;
    }
    std::uint64_t total(std::int64_t loops) const noexcept {
        if (loops < 0) return (std::numeric_limits<std::uint64_t>::max)();
        const auto limit = (std::numeric_limits<std::uint64_t>::max)();
        if (std::uint64_t(loops) > (limit - length) / period) return limit;
        return length + std::uint64_t(loops) * period;
    }
    std::uint64_t physical(std::uint64_t t) const noexcept {
        return t < length ? t : overlap + (t - length) % period;
    }
    template<class Reader>
    Frame at(std::uint64_t t, std::int64_t loops, Reader& reader) const {
        if (loops >= 0 && t >= total(loops)) t = total(loops) - 1;
        const auto position = physical(t);
        const auto pass = t < length ? 0 : 1 + (t - length) / period;
        Frame value = reader.get(position);
        if (overlap && (loops < 0 || pass < std::uint64_t(loops)) && position >= length - overlap) {
            const auto headIndex = position - (length - overlap);
            const Frame head = reader.get(headIndex);
            const float blend = static_cast<float>(headIndex + 1) / static_cast<float>(overlap);
            value.left = finiteAudio(value.left * (1.0f - blend) + head.left * blend);
            value.right = finiteAudio(value.right * (1.0f - blend) + head.right * blend);
        }
        return value;
    }
    template<class Reader>
    Frame render(double t, std::int64_t loops, Reader& reader) const {
        const auto base = static_cast<std::uint64_t>(t);
        const float x = static_cast<float>(t - static_cast<double>(base));
        const Frame a = at(base ? base - 1 : 0, loops, reader);
        const Frame b = at(base, loops, reader);
        const Frame c = at(base + 1, loops, reader);
        const Frame d = at(base + 2, loops, reader);
        const auto cubic = [x](float p0, float p1, float p2, float p3) noexcept {
            return finiteAudio(p1 + 0.5f * x * (p2 - p0 + x *
                (2.0f * p0 - 5.0f * p1 + 4.0f * p2 - p3 + x *
                 (3.0f * (p1 - p2) + p3 - p0))));
        };
        Frame result{cubic(a.left, b.left, c.left, d.left),
                     cubic(a.right, b.right, c.right, d.right)};

        if (loops >= 0) {
            const float gain = static_cast<float>((std::min)(1.0,
                (static_cast<double>(total(loops)) - t) / (sourceRate * rampSeconds)));
            result.left *= gain; result.right *= gain;
        }
        return result;
    }
};

