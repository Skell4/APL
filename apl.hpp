inline float finiteAudio(float v) noexcept {
    if (std::isnan(v)) return 0.0f;
    const float bound = (std::numeric_limits<float>::max)();
    return (std::max)(-bound, (std::min)(bound, v));
}
inline float clampOutput(float v) noexcept {
    return std::isnan(v) ? 0.0f : (std::max)(-1.0f, (std::min)(1.0f, v));
}
inline float addAudio(float a, float b) noexcept { return finiteAudio(a + b); }
inline bool validGain(float v) noexcept { return std::isfinite(v) && v >= 0.0f; }

