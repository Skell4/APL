class Sound {
    std::shared_ptr<detail::Voice> voice_;
    explicit Sound(std::shared_ptr<detail::Voice> v) noexcept : voice_(std::move(v)) {}
    friend class Player;
public:
    Sound() noexcept = default;
    ~Sound() { reset(); }
    Sound(const Sound&) = delete;
    Sound& operator=(const Sound&) = delete;
    Sound(Sound&& other) noexcept : voice_(std::move(other.voice_)) {}
    Sound& operator=(Sound&& other) noexcept {
        if (this != &other) { reset(); voice_ = std::move(other.voice_); }
        return *this;
    }
    void reset() noexcept {
        if (voice_) {
            voice_->retired.store(true, std::memory_order_release);
            voice_->streamStop.store(true, std::memory_order_release);
            voice_.reset();
        }
    }
    bool isValid() const noexcept {
        return voice_ && voice_->alive.load(std::memory_order_acquire) && !voice_->retired.load();
    }
    void play() {
        if (isValid()) voice_->controls.update([](detail::Controls& c) { c.transport = detail::Transport::Playing; ++c.action; });
    }
    void pause() {
        if (isValid()) voice_->controls.update([](detail::Controls& c) { c.transport = detail::Transport::Paused; ++c.action; });
    }
    void stop() {
        if (isValid()) voice_->controls.update([](detail::Controls& c) {
            c.transport = detail::Transport::Stopped; ++c.action; c.seekFrame = 0; ++c.seek;
        });
    }
    void seek(double seconds) {
        if (!isValid() || !std::isfinite(seconds)) return;
        const double frame = (std::max)(0.0, (std::min)(double(voice_->format.frames), seconds * voice_->format.sampleRate));
        voice_->controls.update([frame](detail::Controls& c) { c.seekFrame = static_cast<std::uint64_t>(frame); ++c.seek; });
    }
    bool isPlaying() const noexcept {
        if (!isValid()) return false;
        detail::Controls c;
        if (!voice_->controls.read(c)) return voice_->playing.load(std::memory_order_acquire);
        return c.transport == detail::Transport::Playing &&
               (voice_->completedAction.load() != c.action || voice_->completedSeek.load() != c.seek);
    }
    void setVolume(float volume) {
        if (isValid() && detail::validGain(volume)) voice_->controls.update([volume](detail::Controls& c) {
            c.left = c.right = volume;
        });
    }
    void setLoop(bool enabled) {
        if (isValid()) voice_->controls.update([enabled](detail::Controls& c) {
            const std::int64_t loops = enabled ? -1 : 0;
            if (c.loops != loops) { c.loops = loops; ++c.loopRevision; }
        });
    }
    void setLoopCount(std::uint32_t repetitions) {
        if (isValid()) voice_->controls.update([repetitions](detail::Controls& c) {
            if (c.loops != repetitions) { c.loops = repetitions; ++c.loopRevision; }
        });
    }
};

class Player {
    mutable std::mutex lifecycle_;
    std::shared_ptr<detail::Errors> errors_ = std::make_shared<detail::Errors>();
    std::unique_ptr<detail::Engine> engine_;
public:
    Player() = default;
    ~Player() { shutdown(); }
    Player(const Player&) = delete;
    Player& operator=(const Player&) = delete;
    Player(Player&&) = delete;
    Player& operator=(Player&&) = delete;

    bool init() {
        std::lock_guard<std::mutex> lock(lifecycle_);
        if (engine_) return true;
        try {
            auto engine = std::make_unique<detail::Engine>(errors_);
            std::string error;
            if (!engine->init(error)) { errors_->set(error); return false; }
            engine_ = std::move(engine); errors_->set(""); return true;
        } catch (const std::exception& e) { errors_->set(e.what()); return false; }
        catch (...) { errors_->set("APL: inizializzazione fallita."); return false; }
    }
    void shutdown() noexcept {
        std::lock_guard<std::mutex> lock(lifecycle_);
        if (engine_) {
            engine_->shutdown();
            if (engine_->backend->failure()) {
                try { errors_->set(engine_->backend->failureMessage()); } catch (...) {}
            }
            engine_.reset();
        }
    }
    Sound load(const std::filesystem::path& path, LoadMode mode = LoadMode::Memory) {
        std::lock_guard<std::mutex> lock(lifecycle_);
        if (!engine_) { errors_->set("APL: chiamare Player::init prima di load."); return {}; }
        try {
            if (mode != LoadMode::Memory && mode != LoadMode::Stream) {
                errors_->set("APL: modalita' di caricamento non valida."); return {};
            }
            std::string error;
            std::unique_ptr<detail::Decoder> decoder = detail::openDecoder(path, error);
            if (!decoder) { errors_->set(error); return {}; }
            auto voice = std::make_shared<detail::Voice>(decoder->format(), mode,
                                                        engine_->backend->sampleRate(), errors_);
            errors_->set("");
            if (mode == LoadMode::Memory) {
                if (voice->format.frames > voice->memory.max_size()) {
                    errors_->set("APL: audio troppo grande per la memoria disponibile."); return {};
                }
                voice->memory.resize(static_cast<std::size_t>(voice->format.frames));
                std::size_t read = 0;
                if (!decoder->readFrames(0, voice->memory.size(), voice->memory.data(), read, error) ||
                    read != voice->memory.size()) { errors_->set(error); return {}; }
            } else {
                voice->decoder = std::move(decoder); voice->startWorker();
            }
            if (!engine_->attach(voice)) { errors_->set("APL: limite di 128 suoni raggiunto (rilasciare un Sound)."); return {}; }
            return Sound(std::move(voice));
        } catch (const std::exception& e) { errors_->set(e.what()); return {}; }
        catch (...) { errors_->set("APL: caricamento fallito."); return {}; }
    }
    void setMasterVolume(float volume) {
        if (!detail::validGain(volume)) return;
        std::lock_guard<std::mutex> lock(lifecycle_);
        if (engine_) engine_->master.store(volume, std::memory_order_relaxed);
    }
    std::string lastError() const {
        std::lock_guard<std::mutex> lock(lifecycle_);
        if (engine_) {
            if (engine_->backend->failure()) return engine_->backend->failureMessage();
        }
        return errors_->get();
    }
};

