class ControlMailbox {
    std::mutex writers_;
    std::atomic<std::uint64_t> sequence_{0}, action_{0}, seek_{0}, seekFrame_{0}, loopRevision_{0};
    std::atomic<unsigned> transport_{0};
    std::atomic<std::int64_t> loops_{0};
    std::atomic<float> left_{1}, right_{1};
public:
    bool read(Controls& out) const noexcept {
        const auto before = sequence_.load();
        if (before & 1u) return false;
        Controls c;
        c.transport = static_cast<Transport>(transport_.load());
        c.action = action_.load(); c.seek = seek_.load(); c.seekFrame = seekFrame_.load();
        c.loops = loops_.load(); c.loopRevision = loopRevision_.load();
        c.left = left_.load(); c.right = right_.load();
        if (sequence_.load() != before) return false;
        out = c; return true;
    }
    template<class Function> void update(Function fn) {
        std::lock_guard<std::mutex> lock(writers_);
        Controls c;
        (void)read(c);
        fn(c);
        sequence_.fetch_add(1);
        transport_.store(static_cast<unsigned>(c.transport)); action_.store(c.action);
        seek_.store(c.seek); seekFrame_.store(c.seekFrame);
        loops_.store(c.loops); loopRevision_.store(c.loopRevision);
        left_.store(c.left); right_.store(c.right);
        sequence_.fetch_add(1);
    }
};

struct StreamRequest {
    std::atomic<std::uint64_t> sequence{0}, generation{1};
    std::atomic<double> timeline{0};
    std::atomic<std::int64_t> loops{0};
    void write(std::uint64_t g, double t, std::int64_t l) noexcept {
        sequence.fetch_add(1); generation.store(g); timeline.store(t); loops.store(l);
        sequence.fetch_add(1);
    }
    bool read(std::uint64_t& g, double& t, std::int64_t& l) const noexcept {
        const auto before = sequence.load();
        if (before & 1u) return false;
        const auto ng = generation.load(); const auto nt = timeline.load(); const auto nl = loops.load();
        if (sequence.load() != before) return false;
        g = ng; t = nt; l = nl; return true;
    }
};

