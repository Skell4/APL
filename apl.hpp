struct Mp3Bits {
    const unsigned char* data = nullptr;
    std::size_t position = 0, limit = 0;
    bool good = true;
    Mp3Bits(const unsigned char* bytes, std::size_t size) noexcept : data(bytes), limit(size * 8) {}
    unsigned get(unsigned count) noexcept {
        if (count > 24 || position > limit || count > limit - position) { good = false; return 0; }
        unsigned result = 0;
        for (unsigned n = 0; n < count; ++n, ++position)
            result = (result << 1) | ((data[position / 8] >> (7 - position % 8)) & 1u);
        return result;
    }
};

inline std::uint32_t mp3Be32(const unsigned char* p) noexcept {
    return (std::uint32_t(p[0]) << 24) | (std::uint32_t(p[1]) << 16) |
           (std::uint32_t(p[2]) << 8) | p[3];
}

struct Mp3Header {
    std::uint32_t raw = 0, rate = 0;
    unsigned bytes = 0, channels = 0, bands = 0, samples = 0, side = 0;
    unsigned mode = 0, extension = 0;
    bool mpeg1 = false, crc = false;
    bool parse(std::uint32_t word) noexcept {
        raw = word;
        const unsigned version = (word >> 19) & 3u;
        const unsigned layer = (word >> 17) & 3u;
        const unsigned bitrate = (word >> 12) & 15u;
        const unsigned frequency = (word >> 10) & 3u;
        if ((word & 0xffe00000u) != 0xffe00000u || version == 1 || layer != 1 ||
            !bitrate || bitrate == 15 || frequency == 3) return false;
        static constexpr unsigned rates[3] = {44100, 48000, 32000};
        static constexpr unsigned bitrates[2][16] = {
            {0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160, 0},
            {0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 0}
        };
        mpeg1 = version == 3;
        rate = rates[frequency] >> (mpeg1 ? 0 : version == 2 ? 1 : 2);
        bands = frequency + (mpeg1 ? 0 : version == 2 ? 3 : 6);
        mode = (word >> 6) & 3u; extension = (word >> 4) & 3u;
        channels = mode == 3 ? 1u : 2u;
        crc = !(word & 0x10000u);
        samples = mpeg1 ? 1152u : 576u;
        side = mpeg1 ? (channels == 1 ? 17u : 32u) : (channels == 1 ? 9u : 17u);
        bytes = (mpeg1 ? 144000u : 72000u) * bitrates[mpeg1 ? 1 : 0][bitrate] / rate + ((word >> 9) & 1u);
        return bytes >= 4u + (crc ? 2u : 0u) + side && bytes <= 4096;
    }
};

struct Mp3Granule {
    unsigned partBits = 0, pairs = 0, gain = 0, compress = 0;
    unsigned block = 0, region0 = 0, region1 = 0, table[3]{}, subGain[3]{};
    bool switched = false, mixed = false, pre = false, scale = false, countTable = false;
};
struct Mp3Side {
    unsigned back = 0, reuse[2][4]{};
    Mp3Granule granule[2][2];
    bool parse(const unsigned char* data, const Mp3Header& h) noexcept {
        Mp3Bits bits(data, h.side);
        back = bits.get(h.mpeg1 ? 9u : 8u);
        (void)bits.get(h.mpeg1 ? (h.channels == 1 ? 5u : 3u) : (h.channels == 1 ? 1u : 2u));
        if (h.mpeg1) for (unsigned ch = 0; ch < h.channels; ++ch)
            for (unsigned group = 0; group < 4; ++group) reuse[ch][group] = bits.get(1);
        for (unsigned gr = 0; gr < (h.mpeg1 ? 2u : 1u); ++gr) for (unsigned ch = 0; ch < h.channels; ++ch) {
            auto& g = granule[gr][ch];
            g.partBits = bits.get(12); g.pairs = bits.get(9); g.gain = bits.get(8);
            g.compress = bits.get(h.mpeg1 ? 4u : 9u); g.switched = bits.get(1) != 0;
            if (g.pairs > 288) return false;
            if (g.switched) {
                g.block = bits.get(2); g.mixed = bits.get(1) != 0;
                if (!g.block || (g.mixed && g.block != 2)) return false;
                for (unsigned r = 0; r < 2; ++r) g.table[r] = bits.get(5);
                for (unsigned w = 0; w < 3; ++w) g.subGain[w] = bits.get(3);
                g.region0 = g.block == 2 && !g.mixed ? 8u : 7u;
                g.region1 = 20 - g.region0;
            } else {
                for (unsigned r = 0; r < 3; ++r) g.table[r] = bits.get(5);
                g.region0 = bits.get(4); g.region1 = bits.get(3);
                if (g.region0 + g.region1 > 20) return false;
            }
            for (unsigned r = 0; r < 3; ++r) if (g.table[r] == 4 || g.table[r] == 14) return false;
            g.pre = h.mpeg1 && bits.get(1) != 0;
            g.scale = bits.get(1) != 0; g.countTable = bits.get(1) != 0;
        }
        return bits.good && bits.position == bits.limit;
    }
};

