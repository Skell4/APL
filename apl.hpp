class StreamRing {
    static constexpr std::uint32_t capacity_ = 8192;
    std::array<StreamFrame, capacity_> data_{};
    alignas(64) std::atomic<std::uint32_t> read_{0};
    [[maybe_unused]] std::array<unsigned char, 64 - sizeof(read_)> readPadding_{};
    alignas(64) std::atomic<std::uint32_t> write_{0};
    [[maybe_unused]] std::array<unsigned char, 64 - sizeof(write_)> writePadding_{};
public:
    bool push(const StreamFrame& f) noexcept {
        const auto w = write_.load(std::memory_order_relaxed);
        if (w - read_.load(std::memory_order_acquire) == capacity_) return false;
        data_[w & (capacity_ - 1)] = f;
        write_.store(w + 1, std::memory_order_release); return true;
    }
    bool pop(std::uint64_t generation, StreamFrame& f) noexcept {
        auto r = read_.load(std::memory_order_relaxed);
        const auto end = write_.load(std::memory_order_acquire);

        while (r != end) {
            const auto item = data_[r & (capacity_ - 1)];
            ++r;
            if (item.generation == generation) {
                f = item; read_.store(r, std::memory_order_release); return true;
            }
        }
        read_.store(r, std::memory_order_release); return false;
    }
};

